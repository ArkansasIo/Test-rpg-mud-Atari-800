#!/usr/bin/env bash
set -euo pipefail

# Clone CircleMUD as an isolated reference and generate a corresponding
# RPGMUD assembly port tree. This is a structural/clean-room port generator:
# it does not mechanically translate or copy C implementation bodies.

ROOT="${1:-.}"
REF="${CIRCLEMUD_REF:-$ROOT/reference/CircleMUD}"
PORT="$ROOT/porting/circlemud"
UPSTREAM="${CIRCLEMUD_UPSTREAM_URL:-https://github.com/Yuffster/CircleMUD.git}"
BRANCH="${CIRCLEMUD_BRANCH:-master}"

die() { echo "ERROR: $*" >&2; exit 2; }

command -v git >/dev/null 2>&1 || die "git is required."
mkdir -p "$ROOT/reference" "$PORT"

if [[ -d "$REF/.git" ]]; then
  git -C "$REF" fetch --depth=1 origin "$BRANCH"
  git -C "$REF" checkout --detach FETCH_HEAD
else
  git clone --depth=1 --branch "$BRANCH" "$UPSTREAM" "$REF"
fi

# CircleMUD's public mirror currently keeps C sources in src/.
# Keep a fallback for authorized forks that place them directly in the root.
if [[ -d "$REF/src" ]]; then
  SRC="$REF/src"
elif find "$REF" -maxdepth 2 -type f -name '*.c' -print -quit | grep -q .; then
  SRC="$REF"
else
  die "No CircleMUD C source tree found below $REF."
fi

C_MANIFEST="$PORT/upstream-c-files.txt"
H_MANIFEST="$PORT/upstream-h-files.txt"
: > "$C_MANIFEST"
: > "$H_MANIFEST"

find "$SRC" -type f -name '*.c' -print | LC_ALL=C sort > "$C_MANIFEST"
find "$SRC" -type f -name '*.h' -print | LC_ALL=C sort > "$H_MANIFEST"

C_COUNT=$(wc -l < "$C_MANIFEST" | tr -d ' ')
H_COUNT=$(wc -l < "$H_MANIFEST" | tr -d ' ')

[[ "$C_COUNT" -gt 0 ]] || die "CircleMUD checkout contains no C translation units."

# Each source file gets a matching .asm port target. The generated file contains
# only metadata and entry-point placeholders; it never embeds the upstream body.
while IFS= read -r source; do
  rel="${source#"$SRC"/}"
  stem="${rel%.c}"
  out="$PORT/asm/${stem}.asm"
  mkdir -p "$(dirname "$out")"

  if [[ ! -f "$out" ]]; then
    cat > "$out" <<EOF
; RPGMUD-64 clean-room assembly port target
; Upstream reference: CircleMUD src/$rel
; Generated by: tools/port_circlemud.sh
; STATUS: structural target only; implementation required.
;
; Do not paste the upstream C implementation into this file.
; Map behavior -> RPGMUD-64 ABI -> assembly -> deterministic tests.

PORT_INIT:
        RTS

PORT_TICK:
        RTS
EOF
  fi
done < "$C_MANIFEST"

cat > "$PORT/PORTING_STATUS.md" <<EOF
# CircleMUD Assembly Port Worklist

Generated from:
- Upstream: $UPSTREAM
- Branch: $BRANCH
- Reference checkout: $REF
- C translation units: $C_COUNT
- C headers: $H_COUNT

## Guarantees

1. The reference checkout is isolated under `reference/CircleMUD`.
2. Every discovered `.c` translation unit has a corresponding `.asm` port target.
3. Existing generated implementations are not overwritten by this script.
4. The generated targets contain no copied C implementation bodies.

## Important

A filename-for-filename conversion is not a semantic C-to-assembly compiler.
Each target must be implemented against the RPGMUD-64 ABI and tested.
Review the upstream project's licensing terms before redistributing upstream
source, data, or derivative material.
EOF

echo "CircleMUD reference : $REF"
echo "C translation units : $C_COUNT"
echo "C headers           : $H_COUNT"
echo "Assembly port tree  : $PORT/asm"
echo "STATUS              : generation completed successfully"
