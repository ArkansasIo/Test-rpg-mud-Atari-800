#!/usr/bin/env bash
set -euo pipefail

# Create an isolated CircleMUD reference checkout and an assembly port worklist.
# This does NOT translate C to assembly or copy C implementation bodies into .asm.
# Review upstream license terms before redistributing any upstream files.

ROOT="${1:-.}"
REF="$ROOT/reference/CircleMUD"
PORT="$ROOT/porting/circlemud"
UPSTREAM="${CIRCLEMUD_UPSTREAM_URL:-https://github.com/Yuffster/CircleMUD.git}"

mkdir -p "$ROOT/reference" "$PORT"
if [[ -d "$REF/.git" ]]; then
  git -C "$REF" fetch --depth=1 origin
  git -C "$REF" checkout FETCH_HEAD
else
  git clone --depth=1 "$UPSTREAM" "$REF"
fi

SRC="$REF/src"
if [[ ! -d "$SRC" ]]; then
  echo "ERROR: expected upstream C source directory at $SRC" >&2
  exit 2
fi

# Preserve a local manifest of upstream source filenames for traceability.
find "$SRC" -type f \( -name '*.c' -o -name '*.h' \) -print \
  | LC_ALL=C sort > "$PORT/upstream-c-files.txt"

# Create an assembly porting stub for each C translation unit.
# Stubs deliberately contain no copied upstream implementation.
while IFS= read -r source; do
  [[ "$source" == *.c ]] || continue
  rel="${source#"$SRC"/}"
  stem="${rel%.c}"
  out="$PORT/asm/${stem}.asm"
  mkdir -p "$(dirname "$out")"
  if [[ ! -f "$out" ]]; then
    cat > "$out" <<EOF
; CircleMUD subsystem port stub
; Upstream reference path: src/$rel
; This file is a clean-room assembly implementation placeholder.
; Port the behavior, data layout, error handling and tests deliberately.
; Do not paste upstream C source into this file.
.include "../shared/abi.inc"

PORT_INIT:
        RTS

PORT_TICK:
        RTS
EOF
  fi
done < "$PORT/upstream-c-files.txt"

cat > "$PORT/PORTING_STATUS.md" <<'EOF'
# CircleMUD Assembly Port Worklist

Generated by tools/port_circlemud.sh.

- `upstream-c-files.txt` records upstream C/header paths.
- `asm/` contains one clean-room assembly port stub per upstream C translation unit.
- A stub is not a translated or working implementation.
- Implement and test each subsystem incrementally; do not infer correctness from matching filenames.
- Review upstream license terms and preserve required notices for any use or redistribution of upstream material.
EOF

echo "Reference checkout: $REF"
echo "C/header manifest:  $PORT/upstream-c-files.txt"
echo "Assembly worklist:  $PORT/asm/"
echo "NOTE: generated .asm files are stubs, not automated C-to-assembly translations."
