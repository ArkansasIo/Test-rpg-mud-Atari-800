; Gameplay-to-audio event mapping
AUDIO_EVENT_MOVE=1
AUDIO_EVENT_ATTACK=2
AUDIO_EVENT_HIT=3
AUDIO_EVENT_LOOT=4
AUDIO_EVENT_LEVEL=5
AUDIO_EVENT_CHAT=6
AUDIO_EVENT_LOGIN=7
AUDIO_EVENT_LOGOUT=8
AUDIO_EVENT:
        CMP #AUDIO_EVENT_LOGIN
        BCC AE_DONE
        CMP #AUDIO_EVENT_LOGOUT+1
        BCS AE_DONE
        JSR SFX_PLAY
AE_DONE:
        RTS
