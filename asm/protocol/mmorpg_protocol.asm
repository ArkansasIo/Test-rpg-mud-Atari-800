; RPGMUD MMORPG protocol frame validation
PROTO_MAX_PAYLOAD=240
PROTO_EVT_CHARACTER=$A0
PROTO_EVT_STATS=$A1
PROTO_EVT_QUEST=$A2
PROTO_EVT_PARTY=$A5
PROTO_EVT_GUILD=$A6
PROTO_EVT_DUNGEON=$A8
PROTO_EVT_RAID=$A9
PROTO_EVT_CHAT=$AA
PROTO_EVT_MARKET=$AC
PROTO_OK=0
PROTO_BAD_OPCODE=1
PROTO_BAD_LENGTH=2

PROTO_VALIDATE:
        CMP #PROTO_EVT_CHARACTER
        BCC PV_BAD
        CMP #$AD
        BCS PV_BAD
        LDA #PROTO_OK
        RTS
PV_BAD:
        LDA #PROTO_BAD_OPCODE
        RTS

PROTO_VALIDATE_LENGTH:
        CPY #PROTO_MAX_PAYLOAD+1
        BCC PV_LEN_OK
        LDA #PROTO_BAD_LENGTH
        RTS
PV_LEN_OK:
        LDA #PROTO_OK
        RTS

PROTO_CHARACTER:
        LDA #PROTO_EVT_CHARACTER
        RTS
PROTO_STATS:
        LDA #PROTO_EVT_STATS
        RTS
PROTO_QUEST:
        LDA #PROTO_EVT_QUEST
        RTS
PROTO_PARTY:
        LDA #PROTO_EVT_PARTY
        RTS
PROTO_GUILD:
        LDA #PROTO_EVT_GUILD
        RTS
PROTO_DUNGEON:
        LDA #PROTO_EVT_DUNGEON
        RTS
PROTO_RAID:
        LDA #PROTO_EVT_RAID
        RTS
PROTO_MARKET:
        LDA #PROTO_EVT_MARKET
        RTS
PROTO_CHAT:
        LDA #PROTO_EVT_CHAT
        RTS
