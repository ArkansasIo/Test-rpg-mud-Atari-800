; RPGMUD MMORPG protocol frame validation
PROTO_MAX_PAYLOAD=240
PROTO_CHARACTER=$A0
PROTO_STATS=$A1
PROTO_QUEST=$A2
PROTO_PARTY=$A5
PROTO_GUILD=$A6
PROTO_DUNGEON=$A8
PROTO_RAID=$A9
PROTO_MARKET=$AC
PROTO_CHAT=$AA
PROTO_OK=0
PROTO_BAD_OPCODE=1
PROTO_BAD_LENGTH=2
PROTO_VALIDATE:
        CMP #PROTO_CHARACTER
        BCC PV_BAD
        CMP #$AD
        BCS PV_BAD
        RTS
PV_BAD:
        LDA #PROTO_BAD_OPCODE
        RTS
PROTO_VALIDATE_LENGTH:
        CPY #PROTO_MAX_PAYLOAD+1
        BCC PV_LEN_OK
        LDA #PROTO_BAD_LENGTH
        RTS
PV_LEN_OK:
        LDA #PROTO_OK
        RTS
PROTO_CHARACTER: RTS
PROTO_STATS: RTS
PROTO_QUEST: RTS
PROTO_PARTY: RTS
PROTO_GUILD: RTS
PROTO_DUNGEON: RTS
PROTO_RAID: RTS
PROTO_MARKET: RTS
PROTO_CHAT: RTS
