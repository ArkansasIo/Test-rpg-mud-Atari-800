; Append-only persistence journal
JOURNAL_CAPACITY=64
JOURNAL_ACTIVE:.byte 0
JOURNAL_COUNT:.byte 0
JOURNAL_SEQUENCE:.word 0
JOURNAL_TYPE:.res JOURNAL_CAPACITY
JOURNAL_ID_LO:.res JOURNAL_CAPACITY
JOURNAL_ID_HI:.res JOURNAL_CAPACITY

JOURNAL_BEGIN:
        LDA #1
        STA JOURNAL_ACTIVE
        RTS

JOURNAL_WRITE:
        LDA JOURNAL_ACTIVE
        BEQ JW_FAIL
        LDX JOURNAL_COUNT
        CPX #JOURNAL_CAPACITY
        BCS JW_FAIL
        STA JOURNAL_TYPE,X
        TXA
        STA JOURNAL_ID_LO,X
        LDA #0
        STA JOURNAL_ID_HI,X
        INC JOURNAL_COUNT
        LDA #0
        RTS
JW_FAIL:
        LDA #4
        RTS

JOURNAL_COMMIT:
        LDA JOURNAL_ACTIVE
        BEQ JC_DONE
        LDA JOURNAL_SEQUENCE
        CLC
        ADC #1
        STA JOURNAL_SEQUENCE
        LDA #0
        STA JOURNAL_ACTIVE
        STA JOURNAL_COUNT
JC_DONE:
        RTS

JOURNAL_RECOVER:
        LDA #0
        STA JOURNAL_ACTIVE
        RTS
