; RPGMUD MySQL persistence driver ABI
MYSQL_STATUS_OK=0
MYSQL_STATUS_CONNECT=1
MYSQL_STATUS_QUERY=2
MYSQL_STATUS_RESULT=3
MYSQL_STATUS_TIMEOUT=4
MYSQL_STATUS_NOTFOUND=5

MYSQL_HOST_PTR_LO: .byte 0
MYSQL_HOST_PTR_HI: .byte 0
MYSQL_DB_PTR_LO: .byte 0
MYSQL_DB_PTR_HI: .byte 0
MYSQL_USER_PTR_LO: .byte 0
MYSQL_USER_PTR_HI: .byte 0
MYSQL_PASS_PTR_LO: .byte 0
MYSQL_PASS_PTR_HI: .byte 0
MYSQL_PORT: .word 3306

MYSQL_CONNECT:
        LDA #MYSQL_STATUS_CONNECT
        RTS
MYSQL_DISCONNECT:
        LDA #MYSQL_STATUS_OK
        RTS
MYSQL_BEGIN:
        LDA #MYSQL_STATUS_OK
        RTS
MYSQL_COMMIT:
        LDA #MYSQL_STATUS_OK
        RTS
MYSQL_ROLLBACK:
        LDA #MYSQL_STATUS_OK
        RTS
MYSQL_EXEC:
        LDA #MYSQL_STATUS_QUERY
        RTS
MYSQL_FETCH:
        LDA #MYSQL_STATUS_RESULT
        RTS
