; Versioned fixed-record serialization
SERIALIZE_VERSION=1
SERIALIZE_OK=0
SERIALIZE_BOUNDS=1
SERIALIZE_VERSION_ERR=2
SER_SRC_LO:.byte 0
SER_SRC_HI:.byte 0
SER_DST_LO:.byte 0
SER_DST_HI:.byte 0
SER_LEN:.word 0
SER_VERSION:.byte SERIALIZE_VERSION

SERIALIZE_RECORD:
        LDY #0
SR_COPY:
        CPY SER_LEN
        BCS SR_DONE
        LDA (SER_SRC_LO),Y
        STA (SER_DST_LO),Y
        INY
        BNE SR_COPY
SR_DONE:
        LDA #SERIALIZE_OK
        RTS

DESERIALIZE_RECORD:
        JMP SERIALIZE_RECORD

SERIALIZE_VALIDATE:
        LDA SER_VERSION
        CMP #SERIALIZE_VERSION
        BEQ SV_OK
        LDA #SERIALIZE_VERSION_ERR
        RTS
SV_OK:
        LDA #SERIALIZE_OK
        RTS
